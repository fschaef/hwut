"""SPDX-License: MIT; Project HWUT; (C) Frank-Rene Schaefer
______________________________________________________________________________

PURPOSE: BUILDING THE INSTALLATION PACKAGES (adm/WORK/spec/24). The SAME
         SOFTWARE, DIFFERENT LANDING: every form is cut from one stage.

    python3 adm/packaging/build.py stage <dir>     the stage alone
    python3 adm/packaging/build.py wheel <dir>     hwut-<version>-py3-none-any.whl
    python3 adm/packaging/build.py deb <dir>       hwut_<version>_all.deb
    python3 adm/packaging/build.py image <dir>     ghcr.io/fschaef/hwut:<version>,
                                                   the deb in 'adm/packaging/
                                                   Containerfile'; <dir> the
                                                   build context

ONE SOURCE OF TRUTH. The version is 'adm/version.py'; the dependencies are
the census rows of 'adm/requirement-list.txt' ('services/lib/
requirements.py' reads them); the faces are the shims of 'bin/'
('services/_launch.py' reads them). 'pyproject.toml' is GENERATED into the
stage and never stands in the tree: a second copy of the list would be a
list to keep in step.

THE STAGE is the package 'hwut' as a user receives it:

    in    engine, services, auxiliary, test_writing_support, demo,
          adm/version.py, adm/requirement-list.txt, bin/.hwut.conf,
          doc/HOWTO-*.txt
    out   every TEST directory but the demonstration's, WORK, what a run
          leaves (OUT, TMP, traces, logs, caches), the completion table
          (written by 'hwut --command-line-setup' where it is installed),
          the shims of 'bin/' (an installed face is an entry point,
          '_launch.main'), and the faces 'hwut.dev.*' (developing hwut)
______________________________________________________________________________
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

HWUT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(
           __file__)), "..", ".."))
sys.path.insert(0, os.path.dirname(HWUT))
from hwut.services._launch          import shim_module_db   # noqa: E402
from hwut.services.lib import requirements                  # noqa: E402

TOP_TUPLE  = ("engine", "services", "auxiliary", "test_writing_support",
              "demo")
FILE_TUPLE = ("adm/version.py", "adm/requirement-list.txt",
              "bin/.hwut.conf")
DOC_GLOB_RE = re.compile(r"^HOWTO-.*\.txt$")
KEEP_TEST  = os.path.join("demo", "python", "TEST")
LEFT_BEHIND = ("TMP", "OUT", "WORK", "__pycache__", ".ruff_cache",
               "htmlcov", "hwut-traces*", "hwut.log", ".coverage",
               "_complete_db.py", "*.pyc")
DEV_PREFIX = "hwut.dev."
SUMMARY    = "Tolerant golden-master testing: tests compared with GOOD " \
             "files they are allowed to differ from, within stated bounds."


def version():
    """
    RETURN: str, the version 'adm/version.py' states ('2.0.0').
    """
    with open(os.path.join(HWUT, "adm", "version.py")) as fh:
        return re.search(r"""=\s*["']([^"']+)["']""", fh.read()).group(1)


def face_module_db():
    """
    RETURN: dict, face name -> module, of every face a user receives: the
            shims of 'bin/' but 'hwut.dev.*'.
    """
    return {face: module for face, module in shim_module_db().items()
            if not face.startswith(DEV_PREFIX)}


def _ignored(directory, name_list):
    """
    RETURN: set[str], the names below 'directory' the stage leaves out.
    """
    out = set(shutil.ignore_patterns(*LEFT_BEHIND)(directory, name_list))
    relative = os.path.relpath(directory, HWUT)
    for name in name_list:
        if name == "TEST" and os.path.join(relative, name) != KEEP_TEST:
            out.add(name)
    return out


def stage(target):
    """
    RETURN: str, the project directory written at 'target': 'hwut/' as a
            user receives it, its '_launch_db.py', and 'pyproject.toml'.
    """
    package = os.path.join(target, "hwut")
    os.makedirs(package)
    for top in TOP_TUPLE:
        shutil.copytree(os.path.join(HWUT, top), os.path.join(package, top),
                        ignore=_ignored)
    for relative in FILE_TUPLE:
        os.makedirs(os.path.join(package, os.path.dirname(relative)),
                    exist_ok=True)
        shutil.copy2(os.path.join(HWUT, relative),
                     os.path.join(package, relative))
    os.makedirs(os.path.join(package, "doc"))
    for name in sorted(os.listdir(os.path.join(HWUT, "doc"))):
        if DOC_GLOB_RE.match(name):
            shutil.copy2(os.path.join(HWUT, "doc", name),
                         os.path.join(package, "doc", name))
    module_db = face_module_db()
    with open(os.path.join(package, "services", "_launch_db.py"), "w") as fh:
        fh.write('"""GENERATED by adm/packaging/build.py: face -> module."""\n'
                 "FACE_MODULE_DB = {\n")
        for face in sorted(module_db):
            fh.write("    %r: %r,\n" % (face, module_db[face]))
        fh.write("}\n")
    readme = os.path.join(os.path.dirname(HWUT), "README.md")
    if os.path.isfile(readme): shutil.copy2(readme, target)
    with open(os.path.join(target, "pyproject.toml"), "w") as fh:
        fh.write(pyproject_text(module_db, os.path.isfile(readme)))
    return target


def pyproject_text(module_db, readme_f):
    """
    RETURN: str, the 'pyproject.toml' of the stage: name, version,
            dependencies and one entry point per face, all read off the
            tree.
    """
    line_list = [
        "[build-system]",
        'requires      = ["setuptools>=61"]',
        'build-backend = "setuptools.build_meta"',
        "",
        "[project]",
        'name            = "hwut"',
        'version         = "%s"' % version(),
        'description     = "%s"' % SUMMARY,
        'requires-python = ">=%s"' % requirements.python_least(),
        'license         = { text = "MIT" }',
        'authors         = [{ name = "Frank-Rene Schaefer" }]',
        "dependencies    = [",
    ]
    line_list += ['    "%s",' % d for d in requirements.wheel_dependencies()]
    line_list.append("]")
    if readme_f: line_list.append('readme = "README.md"')
    line_list += ["", "[project.scripts]"]
    line_list += ['"%s" = "hwut.services._launch:main"' % face
                  for face in sorted(module_db)]
    line_list += [
        "",
        "[tool.setuptools]",
        "include-package-data = false",
        "",
        "[tool.setuptools.packages.find]",
        'include    = ["hwut", "hwut.*"]',
        "namespaces = true",
        "",
        "[tool.setuptools.package-data]",
        '"*" = ["*", ".*"]',
    ]
    return "\n".join(line_list) + "\n"


def wheel(out_directory):
    """
    RETURN: str, the path of the wheel built into 'out_directory'.
    Raises subprocess.CalledProcessError where pip fails to build it.
    """
    os.makedirs(out_directory, exist_ok=True)
    with tempfile.TemporaryDirectory() as work:
        project = stage(os.path.join(work, "project"))
        subprocess.run([sys.executable, "-m", "pip", "wheel", "--no-deps",
                        "--quiet", "--wheel-dir", out_directory, project],
                       check=True)
    path = os.path.join(out_directory,
                        "hwut-%s-py3-none-any.whl" % version())
    if not os.path.isfile(path):
        raise FileNotFoundError(path)
    return path


#  THE DEBIAN PACKAGE (spec 24, ruling 4): the stage's 'hwut' where
#  Debian keeps a Python package for every 'python3', one launcher per
#  face in '/usr/bin', the bash completion linked per face. 'Depends' is
#  the list's, in Debian's numbering; nothing is vendored.
DEB_PYTHON = "usr/lib/python3/dist-packages"
DEB_BASH   = "usr/share/bash-completion/completions"
MAINTAINER = "Frank-Rene Schaefer <fschaef@gmail.com>"
LAUNCHER   = """#! /usr/bin/python3
# SPDX-License: MIT; Project HWUT; (C) Frank-Rene Schaefer
# The face '%s' of the Debian package: 'services/_launch.py' runs the
# module the face names, as '__main__'.
from hwut.services._launch import main
main()
"""
#  WHAT THE PACKAGE LEAVES IS ITS OWN TO TAKE: setup writes the
#  completion table, py3compile the byte code; neither is dpkg's, so
#  prerm removes both and 'apt remove hwut' leaves no file of hwut.
POSTINST = """#! /bin/sh
set -e
if [ "$1" = configure ]; then
    if command -v py3compile > /dev/null 2>&1; then py3compile -p hwut; fi
    /usr/bin/hwut --command-line-setup > /dev/null 2>&1 || true
fi
"""
PRERM = """#! /bin/sh
set -e
rm -f /%s/hwut/services/_complete_db.py
if command -v py3clean > /dev/null 2>&1; then py3clean -p hwut; fi
find /%s/hwut -name __pycache__ -type d -prune -exec rm -rf {} + 2>/dev/null || true
""" % (DEB_PYTHON, DEB_PYTHON)


def control_text(installed_kb):
    """
    RETURN: str, the 'DEBIAN/control' of the package: its version from
            'adm/version.py', its 'Depends' from the list.
    """
    return "\n".join([
        "Package: hwut",
        "Version: %s" % version(),
        "Architecture: all",
        "Maintainer: %s" % MAINTAINER,
        "Installed-Size: %i" % installed_kb,
        "Depends: %s" % requirements.debian_depends(),
        "Section: devel",
        "Priority: optional",
        "Homepage: https://github.com/fschaef/hwut",
        "Description: tolerant golden-master testing",
        " %s" % SUMMARY,
        ""])


def deb(out_directory):
    """
    RETURN: str, the path of 'hwut_<version>_all.deb' built into
            'out_directory'.
    Raises subprocess.CalledProcessError where 'dpkg-deb' fails.
    """
    os.makedirs(out_directory, exist_ok=True)
    with tempfile.TemporaryDirectory() as work:
        project = stage(os.path.join(work, "project"))
        root    = os.path.join(work, "root")
        python  = os.path.join(root, DEB_PYTHON)
        os.makedirs(python)
        shutil.move(os.path.join(project, "hwut"), python)
        os.makedirs(os.path.join(root, "usr", "bin"))
        os.makedirs(os.path.join(root, DEB_BASH))
        shell = "/%s/hwut/services/shell/hwut.bash" % DEB_PYTHON
        for face in sorted(face_module_db()):
            path = os.path.join(root, "usr", "bin", face)
            with open(path, "w") as fh: fh.write(LAUNCHER % face)
            os.chmod(path, 0o755)
            os.symlink(shell, os.path.join(root, DEB_BASH, face))
        doc = os.path.join(root, "usr", "share", "doc", "hwut")
        os.makedirs(doc)
        shutil.copy2(os.path.join(os.path.dirname(HWUT), "LICENSE"),
                     os.path.join(doc, "copyright"))
        for directory, _, name_list in os.walk(root):
            os.chmod(directory, 0o755)
            for name in name_list:
                path = os.path.join(directory, name)
                if not os.path.islink(path) and \
                   not path.startswith(os.path.join(root, "usr", "bin")):
                    os.chmod(path, 0o644)
        size = 0
        for directory, _, name_list in os.walk(root):
            size += sum(os.lstat(os.path.join(directory, n)).st_size
                        for n in name_list)
        debian = os.path.join(root, "DEBIAN")
        os.makedirs(debian)
        with open(os.path.join(debian, "control"), "w") as fh:
            fh.write(control_text((size + 1023) // 1024))
        for name, text in (("postinst", POSTINST), ("prerm", PRERM)):
            path = os.path.join(debian, name)
            with open(path, "w") as fh: fh.write(text)
            os.chmod(path, 0o755)
        path = os.path.join(out_directory, "hwut_%s_all.deb" % version())
        subprocess.run(["dpkg-deb", "--root-owner-group", "-Zxz", "--build",
                        root, path], check=True, stdout=subprocess.DEVNULL)
    return path


IMAGE = "ghcr.io/fschaef/hwut"


def engine():
    """
    RETURN: str, the container engine that answers -- podman before
            docker.
            None, where neither answers.
    """
    for name in ("podman", "docker"):
        path = shutil.which(name)
        if path and subprocess.run([path, "info"], stdout=subprocess.DEVNULL,
                                   stderr=subprocess.DEVNULL).returncode == 0:
            return path
    return None


def image(context_directory):
    """
    RETURN: str, the tag of the runtime image built from the deb of this
            tree, in 'context_directory': '<IMAGE>:<version>', also tagged
            ':latest'.
    Raises OSError where no container engine answers, and
    subprocess.CalledProcessError where the build fails.
    """
    tool = engine()
    if tool is None:
        raise OSError("no container engine answers (podman, docker)")
    os.makedirs(context_directory, exist_ok=True)
    shutil.move(deb(context_directory),
                os.path.join(context_directory, "hwut.deb"))
    shutil.copy2(os.path.join(HWUT, "adm", "packaging", "Containerfile"),
                 os.path.join(context_directory, "Containerfile"))
    tag = "%s:%s" % (IMAGE, version())
    subprocess.run([tool, "build", "--quiet", "--build-arg",
                    "VERSION=%s" % version(), "-t", tag, "-t",
                    IMAGE + ":latest", "-f",
                    os.path.join(context_directory, "Containerfile"),
                    context_directory], check=True, stdout=subprocess.DEVNULL)
    return tag


def main(argv):
    """
    RETURN: 0, the form was built and its path printed.
            2, the command line cannot be read.
            1, the build failed (said on stderr).
    """
    if len(argv) != 2 or argv[0] not in ("stage", "wheel", "deb", "image"):
        sys.stderr.write("usage: build.py stage|wheel|deb|image <dir>\n")
        return 2
    command, directory = argv
    try:
        if command == "stage":
            if os.path.exists(directory) and os.listdir(directory):
                sys.stderr.write("REFUSED: '%s' is not empty\n" % directory)
                return 2
            print("STAGED: %s" % stage(directory))
        elif command == "wheel":
            print("BUILT: %s" % wheel(directory))
        elif command == "deb":
            print("BUILT: %s" % deb(directory))
        else:
            print("BUILT: %s" % image(directory))
    except (OSError, subprocess.CalledProcessError) as error:
        sys.stderr.write("FAILED: %s\n" % error)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
